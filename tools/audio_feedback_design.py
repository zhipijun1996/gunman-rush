#!/usr/bin/env python3
"""Sample-based hurt/wall revision. Reuse V3 DSP, preserve all selected originals."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import shutil
import tempfile

import audio_candidates_v3 as dsp

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config/audio_director/feedback_05"
DEST = ROOT / "assets/audio/feedback_05"
VERSION = "audio-feedback-v1"


def read(path):
    return json.loads(Path(path).read_text())


def write(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def local(name):
    path = ROOT / name.removeprefix("res://")
    if path.is_symlink() or not path.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError("Feedback path escapes repository")
    return path


def bindings():
    return {"recipe_sha256": dsp.digest(CONFIG / "recipes.json"),
            "sources_sha256": dsp.digest(CONFIG / "sources.json"),
            "pipeline_sha256": dsp.digest(Path(__file__)),
            "processor_sha256": dsp.digest(ROOT / "tools/audio_candidates_v3.py")}


def inputs():
    config = read(CONFIG / "recipes.json")
    sources = read(CONFIG / "sources.json")["sources"]
    if config["version"] != VERSION or config["sample_rate"] != dsp.RATE or [e["id"] for e in config["events"]] != ["hurt", "wall"]:
        raise ValueError("Feedback configuration identity changed")
    if [take["id"] for e in config["events"] for take in e["takes"]] != ["hurt_1", "hurt_2", "wall_1", "wall_2", "wall_3"]:
        raise ValueError("Expected two hurt and three wall takes")
    for name, expected in config["locked_inputs"].items():
        if not local(name).is_file() or dsp.digest(local(name)) != expected:
            raise ValueError("Protected selected/BGM/processor input drift: " + name)
    for sid, source in sources.items():
        if source["license"] != "CC0-1.0" or source["commercial_use"] is not True or source["attribution_required"] is not False:
            raise ValueError("Unreviewed commercial source: " + sid)
        registry = local(source["source_registry_path"])
        if dsp.digest(registry) != source["source_registry_sha256"]:
            raise ValueError("Original source registry drift")
        original = read(registry)["sources"][source["source_registry_id"]]
        if any(source.get(key) != value for key, value in original.items()):
            raise ValueError("Original source metadata differs: " + sid)
        for path_key, hash_key in [("path", "sha256"), ("license_path", "license_sha256")]:
            if dsp.digest(local(source[path_key])) != source[hash_key]:
                raise ValueError("Original/license fingerprint drift: " + sid)
        if "source_page_path" in source and dsp.digest(local(source["source_page_path"])) != source["source_page_sha256"]:
            raise ValueError("Source page fingerprint drift: " + sid)
        if local(source["path"]).stat().st_size != source["bytes"]:
            raise ValueError("Original size changed: " + sid)
    for event in config["events"]:
        for take in event["takes"]:
            if not take["layers"] or len(take["layers"]) > 2:
                raise ValueError("Expected one body and optional short texture layer")
            for layer in take["layers"]:
                if layer["source"] not in sources or not 0 < layer["clip_seconds"] <= .2 or not 0 < layer["gain"] <= 1 or abs(layer["pitch_semitones"]) > 5:
                    raise ValueError("Invalid feedback layer bounds")
    return config, sources


def render(event, take, sources, config, stage):
    path = stage / (take["id"] + ".wav")
    actual = dsp.render(event, take, sources, config, path)
    # V3 render records a real temporary path. Publish its canonical runtime
    # identity after the exact generated bytes and original trace are known.
    actual["path"] = "res://assets/audio/feedback_05/" + path.name
    actual["take_id"] = take["id"]
    return actual


def event_record(event, renders, config, sources):
    ids = list(dict.fromkeys(layer["source"] for take in event["takes"] for layer in take["layers"]))
    paths = [row["path"] for row in renders]
    return {"id": event["id"], "label": event["label"], "category": event["category"],
            "max_seconds": event["max_seconds"], "target_rms_dbfs": event["target_rms_dbfs"],
            "candidates": [{"id": event["candidate_id"], "profile": "A", "label": "柔软反馈修订候选",
                "version": config["version"], "path": paths[0], "variants": paths,
                "source_ids": ids, "raw_sources": [sources[sid]["path"] for sid in ids],
                "subjective_status": "awaiting-user", "renders": renders,
                "variant_policy": "Authored samples: hurt uses two distinct body originals and different cloth crops; wall uses three different stone originals. Not separate new field recording sessions."}]}


def build():
    before = bindings()
    config, sources = inputs()
    stage_root = ROOT / "build/audio_feedback_05"
    stage_root.mkdir(parents=True, exist_ok=True)
    (stage_root / ".gdignore").write_text("")
    with tempfile.TemporaryDirectory(prefix="render-", dir=stage_root) as folder:
        stage = Path(folder)
        events = []
        for event in config["events"]:
            takes = [render(event, take, sources, config, stage) for take in event["takes"]]
            events.append(event_record(event, takes, config, sources))
        inputs()  # Recheck actual originals, licenses, selected files and BGM.
        if bindings() != before:
            raise ValueError("Feedback inputs changed during render")
        manifest = {"schema_version": 1, "version": VERSION, "task": config["task"], **before,
                    "profiles": config["profiles"], "sample_rate": config["sample_rate"],
                    "peak_ceiling_dbfs": config["peak_ceiling_dbfs"], "events": events,
                    "sources": sources, "locked_inputs": config["locked_inputs"],
                    "runtime_gain_estimates": config["runtime_gain_estimates"],
                    "runtime_default": "original", "subjective_status": "awaiting-user",
                    "ffmpeg_version": dsp.version(),
                    "scope": "Explicit feedback revision candidates only; source-based DSP success does not approve timbre or real-game mix."}
        DEST.mkdir(parents=True, exist_ok=True)
        for path in stage.glob("*.wav"):
            shutil.move(str(path), DEST / path.name)
        write(DEST / "manifest.json", manifest)
    validate()


def validate():
    config, sources = inputs()
    manifest = read(DEST / "manifest.json")
    for key, value in bindings().items():
        if manifest.get(key) != value:
            raise ValueError("Feedback fingerprint drift: " + key)
    expected_metadata = {"version": VERSION, "task": config["task"], "profiles": config["profiles"],
                         "sample_rate": config["sample_rate"], "peak_ceiling_dbfs": config["peak_ceiling_dbfs"],
                         "sources": sources, "locked_inputs": config["locked_inputs"],
                         "runtime_gain_estimates": config["runtime_gain_estimates"], "runtime_default": "original",
                         "subjective_status": "awaiting-user", "ffmpeg_version": dsp.version()}
    if any(manifest.get(key) != value for key, value in expected_metadata.items()):
        raise ValueError("Feedback manifest metadata changed")
    stage_root = ROOT / "build/audio_feedback_05"
    stage_root.mkdir(parents=True, exist_ok=True)
    (stage_root / ".gdignore").write_text("")
    expected_events = []
    with tempfile.TemporaryDirectory(prefix="rederive-", dir=stage_root) as folder:
        stage = Path(folder)
        for event in config["events"]:
            takes = []
            for take in event["takes"]:
                derived = render(event, take, sources, config, stage)
                path = local(derived["path"])
                actual = dsp.measure(path)
                if any(derived.get(key) != value for key, value in actual.items()):
                    raise ValueError("Feedback output differs from recomputed recipe: " + take["id"])
                if actual["peak_dbfs"] > config["peak_ceiling_dbfs"] + .002 or actual["rms_dbfs"] < -50 or actual["duration"] > event["max_seconds"] + .001:
                    raise ValueError("Feedback output level/duration invalid")
                takes.append(derived)
            expected_events.append(event_record(event, takes, config, sources))
    if manifest.get("events") != expected_events:
        raise ValueError("Feedback candidate identity/variant/DSP trace differs")
    inputs()
    print("AUDIO_FEEDBACK_DESIGN_OK hurt_takes=2 wall_takes=3 selected_and_bgm_unchanged=true")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "validate"])
    args = parser.parse_args()
    {"build": build, "validate": validate}[args.command]()


if __name__ == "__main__":
    main()
