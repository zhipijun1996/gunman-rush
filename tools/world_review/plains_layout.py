# Q is a quadratic shoulder/cove, not decorative random edge noise.
def outline(vertices):
    points=[]
    for value in vertices:
        if len(value)==2:points.append(value)
        else:
            _,cx,cy,x,y=value;ax,ay=points[-1]
            for i in range(1,7):
                t=i/6
                points.append(((1-t)**2*ax+2*(1-t)*t*cx+t*t*x,(1-t)**2*ay+2*(1-t)*t*cy+t*t*y))
    poly=Polygon(points)
    assert poly.is_valid
    return poly

