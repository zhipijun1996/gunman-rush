def build_layout(edges):
    geometry={f'P-R{n:02}':outline(vertices) for n,vertices in SHAPES.items()}
    corridors={};ends={};paths={}
    assert len(PASSAGES)==len(edges)==43
    for e in edges:
        a,b=int(e['a'][-2:]),int(e['b'][-2:]);key=tuple(sorted((a,b)))
        line,width=PASSAGES[key];ps=list(line)
        if a!=key[0]:ps=ps[::-1]
        for i,r in [(0,e['a']),(-1,e['b'])]:
            if not geometry[r].covers(Point(ps[i])):ps[i]=nearest_points(geometry[r],Point(ps[i]))[0].coords[0]
        line=LineString(ps) if len(set(ps))>1 else Point(ps[0])
        corridors[e['id']]=line.buffer(width,cap_style=3,join_style=2)
        ends[e['id']]=(ps[0],ps[-1]);paths[e['id']]=ps
    return geometry,corridors,ends,paths
