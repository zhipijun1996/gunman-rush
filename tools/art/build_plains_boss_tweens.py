#!/usr/bin/env python3
"""Measure bidirectional pose correspondence; alpha-clean existing pixels, never paint.

Requires numpy, scipy, Pillow and opencv-python-headless. Flow PNGs encode vector
DATA (not artwork). The renderer warps both authored poses to the same intermediate
geometry before sampling their native nearest pixels; alpha remains a cutout.
"""
from pathlib import Path
import sys,json,hashlib
import numpy as np
from PIL import Image
from scipy import ndimage
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'build/art-python'))
import cv2
ROOT=Path(__file__).resolve().parents[2]
SRC=ROOT/'assets/plains_actors_142/atlases'
OUT=ROOT/'assets/plains_boss_motion_142'
RANGE=64.0


def clear_cavity(frame, point, pivot):
    a=np.array(frame);h,w=a.shape[:2];y,x=np.indices((h,w));cx,cy=np.array(point)+pivot
    # Remove only large near-black matte islands inside the open bell arch.
    dark=(a[:,:,:3].max(2)<35)&(a[:,:,3]>0)&(abs(x-cx)<40)&(y>cy-50)&(y<cy+25)
    labels,_=ndimage.label(dark);areas=np.bincount(labels.ravel());areas[0]=0
    erase=areas[labels]>=65
    a[erase]=0
    return Image.fromarray(a),int(erase.sum())


def barrel_mask(frame, region, mouth, pivot):
    a=np.array(frame).astype(float);h,w=a.shape[:2];y,x=np.indices((h,w));rx,ry,rw,rh=region
    roi=(x>=rx-45)&(x<rx+rw+10)&(y>=ry-8)&(y<ry+rh+3)
    # The entire copper silhouette includes dark oxidised metal and the mouth,
    # not only bright gold. Colour/ROI excludes teal cloth and the stone arch.
    bronze=(a[:,:,0]>=a[:,:,1]*1.10)&(a[:,:,1]>=a[:,:,2]*1.15)
    bronze|=a[:,:,:3].max(2)<22
    mask=ndimage.binary_closing(bronze&roi&(a[:,:,3]>0),iterations=2)&roi
    labels,n=ndimage.label(mask);mx,my=np.array(mouth)+pivot
    candidates=[]
    for k in range(1,n+1):
        yy,xx=np.nonzero(labels==k)
        if len(xx)>20:candidates.append((np.mean((xx-mx)**2+(yy-my)**2),k))
    if not candidates:raise ValueError('No isolated copper barrel')
    mask=ndimage.binary_fill_holes(ndimage.binary_dilation(labels==min(candidates)[1],iterations=2))&roi&(a[:,:,3]>0)

    return mask


def main():
    OUT.mkdir(exist_ok=True)
    rows=[];canonical=None
    names=[p.stem for p in SRC.glob('*.json') if p.stem.startswith(('bellstrider','windkeeper')) and p.stem.endswith(('_flow','_motion','_turn'))]
    for name in sorted(names):
        if len(sys.argv)>1 and name not in sys.argv[1:]:continue
        meta=json.loads((SRC/f'{name}.json').read_text());atlas=Image.open(SRC/f'{name}.png').convert('RGBA');w,h=meta['frame_size'];cols=meta['columns'];frames=[];cleaned=0
        for i in range(cols*len(meta['states'])):
            f=atlas.crop((i%cols*w,i//cols*h,(i%cols+1)*w,(i//cols+1)*h))
            if name.startswith('bellstrider'):
                f,n=clear_cavity(f,meta['core_points'][i],meta['pivot']);cleaned+=n
            if name=='bellstrider_lob_flow':
                mask=barrel_mask(f,meta['barrel_regions'][i],meta['muzzle_points'][i],meta['pivot'])
                a=np.array(f)
                if i==0:
                    part=a.copy();part[~mask]=0;canonical=Image.fromarray(part)
                    canonical.save(OUT/'bellstrider_mortar.png')
                    # Retain the source's physical joint and muzzle, no guessed pivot.
                    data={'pivot':meta['pivot'],'joint':meta['barrel_pivots'][0],'muzzle':meta['muzzle_points'][0],'frame_size':[w,h]}
                    (OUT/'mortar.json').write_text(json.dumps(data,indent=2)+'\n')
                    (ROOT/'game/presentation/actors/art/plains_mortar_geometry.gd').write_text('extends RefCounted\n## Measured from the isolated source barrel; generated by build_plains_boss_tweens.py.\n'+''.join('const '+k.upper()+' := Vector2('+str(v[0])+','+str(v[1])+')\n' for k,v in data.items()))
                a[mask]=0;f=Image.fromarray(a)
            frames.append(f)
        if name.startswith('bellstrider'):
            body=Image.new('RGBA',atlas.size)
            for i,f in enumerate(frames):body.paste(f,(i%cols*w,i//cols*h))
            body.save(OUT/f'{name}_body.png')
        # Full-resolution matching followed by quarter-resolution VECTOR storage.
        # Native RGB artwork is neither resampled nor replaced by the optical flow.
        fw,fh=(w+3)//4,(h+3)//4
        packed=Image.new('RGBA',(fw*cols,fh*len(meta['states'])))
        solver=cv2.DISOpticalFlow_create(cv2.DISOPTICAL_FLOW_PRESET_MEDIUM)
        solver.setFinestScale(0)
        gray=[]
        for f in frames:
            a=np.array(f);g=cv2.cvtColor(a[:,:,:3],cv2.COLOR_RGB2GRAY)
            g=np.where(a[:,:,3]>0,48+g.astype(float)*.8,0).astype(np.uint8)
            gray.append(g)
        for i,g in enumerate(gray):
            row,col=divmod(i,cols);loop=meta['states'][row] in ('idle','move')
            stride=2 if name.endswith(('_flow','_motion')) else 1
            j=row*cols+(col+stride)%cols if loop else min(i+stride,row*cols+cols-1)
            forward=solver.calc(g,gray[j],None) if i!=j else np.zeros((h,w,2),np.float32)
            backward=solver.calc(gray[j],g,None) if i!=j else forward.copy()
            flow=np.concatenate((forward,backward),axis=2)
            flow=cv2.resize(flow,(fw,fh),interpolation=cv2.INTER_AREA)
            encoded=np.rint(np.clip(flow/RANGE,-1,1)*127+128).astype(np.uint8)
            packed.paste(Image.fromarray(encoded),(col*fw,row*fh))
        packed.save(OUT/f'{name}_vectors.png')
        rows.append({'id':name,'cell':[fw,fh],'range':RANGE,'source_sha256':hashlib.sha256((SRC/f'{name}.png').read_bytes()).hexdigest(),'alpha_matte_pixels_removed':cleaned})
        print(name,'measured',len(frames),'poses; alpha matte',cleaned,flush=True)
    if len(sys.argv)>1 and (OUT/'manifest.json').exists():
        rows+= [r for r in json.loads((OUT/'manifest.json').read_text()) if r['id'] not in sys.argv[1:]]
    for row in rows:
        row['render_keys']='original_even_columns' if row['id'].endswith(('_flow','_motion')) else 'all_turn_poses'
        for suffix in ('vectors','body'):
            output=OUT/(row['id']+'_'+suffix+'.png')
            if output.exists():row[suffix+'_sha256']=hashlib.sha256(output.read_bytes()).hexdigest()
    (OUT/'manifest.json').write_text(json.dumps(sorted(rows,key=lambda r:r['id']),indent=2)+'\n')

if __name__=='__main__':main()
